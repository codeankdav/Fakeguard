import { useRoute } from "wouter";
import { useGetSharedArticle, getGetSharedArticleQueryKey } from "@workspace/api-client-react";
import { AnalysisResult } from "@/components/analysis-result";
import { Skeleton } from "@/components/ui/skeleton";
import { ShieldCheck, ArrowRight } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Link } from "wouter";

export default function SharedArticle() {
  const [, params] = useRoute("/shared/:shareToken");
  const shareToken = params?.shareToken || "";

  const { data: article, isLoading, isError } = useGetSharedArticle(
    shareToken,
    { query: { enabled: !!shareToken, queryKey: getGetSharedArticleQueryKey(shareToken) } }
  );

  return (
    <div className="min-h-screen bg-background flex flex-col">
      {/* Public Header */}
      <header className="sticky top-0 z-50 w-full border-b bg-background/95 backdrop-blur supports-[backdrop-filter]:bg-background/60">
        <div className="container flex h-14 items-center justify-between">
          <Link href="/">
            <div className="flex items-center gap-2 font-bold text-lg tracking-tight cursor-pointer">
              <ShieldCheck className="h-6 w-6 text-primary" />
              <span>FakeGuard</span>
            </div>
          </Link>
          <div className="flex items-center gap-4">
            <Link href="/sign-up">
              <Button size="sm" className="gap-2 hidden sm:flex">
                Try FakeGuard <ArrowRight className="h-4 w-4" />
              </Button>
            </Link>
          </div>
        </div>
      </header>

      <main className="flex-1 py-8">
        <div className="container max-w-5xl mx-auto px-4">
          <div className="mb-8 p-4 bg-primary/10 border border-primary/20 rounded-lg text-sm flex items-center justify-between flex-wrap gap-4">
            <div>
              <span className="font-semibold text-primary">Public Analysis Record.</span> This is a verified forensic report generated by FakeGuard AI.
            </div>
            <Link href="/sign-up">
              <Button size="sm" variant="outline" className="shrink-0">
                Run Your Own Analysis
              </Button>
            </Link>
          </div>

          {isLoading ? (
            <div className="space-y-8 animate-pulse">
              <Skeleton className="h-64 w-full rounded-xl" />
              <Skeleton className="h-48 w-full rounded-xl" />
              <div className="grid grid-cols-1 lg:grid-cols-2 gap-8">
                <Skeleton className="h-64 w-full rounded-xl" />
                <Skeleton className="h-64 w-full rounded-xl" />
              </div>
            </div>
          ) : isError || !article ? (
            <div className="text-center py-20 border rounded-xl bg-card">
              <ShieldCheck className="h-12 w-12 text-muted-foreground mx-auto mb-4 opacity-50" />
              <h2 className="text-2xl font-bold mb-2">Report Not Found</h2>
              <p className="text-muted-foreground max-w-md mx-auto mb-6">
                This public share link is invalid or has expired.
              </p>
              <Link href="/">
                <Button>Go to FakeGuard Home</Button>
              </Link>
            </div>
          ) : (
            <AnalysisResult article={article} />
          )}
        </div>
      </main>

      <footer className="border-t py-8 bg-card mt-auto">
        <div className="container mx-auto px-4 text-center text-sm text-muted-foreground">
          <p>© {new Date().getFullYear()} FakeGuard. A professional credibility instrument.</p>
        </div>
      </footer>
    </div>
  );
}